/**
 * PHASE 15 — MATTE BENCHMARK SYSTEM. The permanent still-image benchmark
 * dataset: every category and subcategory named in the phase brief, each
 * with a deterministic synthetic generator (see scene-builder.ts for why
 * synthetic-with-exact-ground-truth, not real photos). "Permanent" here
 * means the STRUCTURE (this manifest + its generators) is what's permanent
 * and versioned in the repo — not a large binary asset folder, which would
 * bloat the repo and can be regenerated byte-identically any time
 * (`build()` has no randomness that isn't seeded).
 */

export type BenchmarkCategory = "easy" | "medium" | "hard";

export interface DatasetCase {
  id: string;
  category: BenchmarkCategory;
  subcategory: string;
  /** Human-readable description — always states plainly that this is a synthetic proxy for the named real-world difficulty, not a real photo. */
  description: string;
  width: number;
  height: number;
  build: () => SyntheticScene;
}

const W = 480;
const H = 480;

const SKIN: RgbColor = { r: 224, g: 184, b: 152 };
const SHIRT: RgbColor = { r: 40, g: 70, b: 110 };
const PLAIN_BG: RgbColor = { r: 235, g: 235, b: 235 };

function personMask(opts: Parameters<typeof drawHumanoidMask>[2] = {}): ReturnType<typeof drawHumanoidMask> {
  return drawHumanoidMask(W, H, opts);
}

